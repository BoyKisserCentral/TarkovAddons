    inline Il2CppObject* start_load()
    {
        // write bundle to file

        char* p_value;
        size_t len;
        errno_t _ = _dupenv_s(&p_value, &len, "APPDATA");
        std::string path = std::string(p_value) + "\\TarkovAddons";
        CreateDirectory(std::wstring(path.begin(), path.end()).c_str(), nullptr);
        const std::string file_path = path + "\\" + "tarkovutils";
        std::ofstream ot(file_path, std::ios::binary);
        ot.write(reinterpret_cast<const char*>(tarkovutils_chams_bundle),
                 tarkovutils_chams_bundle_size);
        ot.close();

        // load bundle into unity
        asset_bundle_module = il2utils::resolve_image("UnityEngine.AssetBundleModule.dll");
        core_module = il2utils::resolve_image("UnityEngine.CoreModule.dll");
        const Il2CppClass* asset_bundle_class = il2utils::resolve_class(asset_bundle_module, "UnityEngine",
                                                                        "AssetBundle");
        const auto load_from_file = il2utils::get_method<Il2CppObject*(*)(Il2CppString*)>(
            asset_bundle_class, "LoadFromFileAsync", 1);

        Il2CppString* il2_path = il2cpp::il2cpp_string_new(file_path.c_str());
        Il2CppObject* request_object = load_from_file(il2_path);

        return request_object;
    }

    inline bool check_progress(Il2CppObject* request_object)
    {
        auto async_operation = new Il2CppObjectInstance(request_object);

        const auto is_done = async_operation->get_method<bool(*)(Il2CppObject*)>("get_isDone", 0);
        const auto get_progress = async_operation->get_method<float(*)(Il2CppObject*)>("get_progress", 0);
        if (is_done(request_object))
        {
            auto asset_bundle_request = new Il2CppObjectInstance(request_object);

            asset_bundle = asset_bundle_request->get_method<Il2CppObject*(*)(Il2CppObject*)>(
                "get_assetBundle", 0)(request_object);
            logger::info("Loaded Asset Bundle");

            // delete file
            char* p_value;
            size_t len;
            errno_t _ = _dupenv_s(&p_value, &len, "APPDATA");
            std::string path = std::string(p_value) + "\\TarkovAddons";
            CreateDirectory(std::wstring(path.begin(), path.end()).c_str(), nullptr);
            const std::string file_path = path + "\\" + "tarkovutils";
            DeleteFileA(file_path.c_str());

            return true;
        }
        logger::info("Progress: " + std::to_string(static_cast<int>(get_progress(request_object) * 100)) + "%");

        return false;
    }

    inline Il2CppObject* load_asset(const char* name, Il2CppObject* system_type)
    {
        auto asset_bundle_instance = new Il2CppObjectInstance(asset_bundle);

        auto load_asset = asset_bundle_instance->get_method<Il2CppObject*(*)(
            Il2CppObject*, Il2CppString*, Il2CppObject*)>("LoadAsset", 2);
        Il2CppString* il2string = il2cpp::il2cpp_string_new(name);
        return load_asset(asset_bundle, il2string, system_type);
    }
